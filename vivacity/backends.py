from typing import Protocol, Any


class Backend(Protocol):
    version: str
    action_schema: dict

    def create_world(self, config: dict, seed: int) -> Any: ...
    def observe(self, world: Any) -> dict: ...
    def snapshot(self, world: Any) -> dict: ...
    def fork(self, state: dict) -> Any: ...
    def apply_action(self, world: Any, action: dict) -> None: ...
    def simulate(self, world: Any, limits: dict) -> dict: ...
    def evaluate(self, world: Any, result: dict) -> dict: ...
    def commit(self, state: dict) -> dict: ...
    def replay(self, branch: dict) -> dict: ...
