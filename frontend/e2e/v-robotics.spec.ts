import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs';
import path from 'node:path';

const shots=path.resolve('../artifacts/v-robotics-browser');
fs.mkdirSync(shots,{recursive:true});

test('precision assembly runs real physics, replays and responds to a tighter tolerance',async({page})=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/workspace');
  await expect(page.getByRole('heading',{name:'Physical experiments'})).toBeVisible();
  await page.getByRole('button',{name:'Browse programs'}).click();
  await expect(page.locator('.v-program-row')).toHaveCount(4);
  await page.getByRole('button',{name:'Humanoids',exact:true}).click();
  await expect(page.locator('.v-program-row')).toHaveCount(3);
  await expect(page.getByRole('button',{name:'Open experiment'})).toHaveCount(0);
  await page.getByRole('button',{name:'Robotic arms',exact:true}).click();
  await page.getByRole('button',{name:'Open experiment'}).click();
  await expect(page.getByRole('heading',{name:'Configure experiment'})).toBeVisible({timeout:45_000});
  await expect(page.getByLabel('Object mass (kg)')).toHaveValue('0.15');
  await expect(page.getByText('Precision assembly controls')).toBeVisible();
  await expect(page.getByRole('button',{name:'Start experiments'})).toBeEnabled({timeout:45_000});
  await page.screenshot({path:path.join(shots,'precision-idle.png'),fullPage:true});
  await page.getByRole('button',{name:'Start experiments'}).click();
  await expect(page.getByRole('heading',{name:'Precision assembly verification'})).toBeVisible({timeout:240_000});
  await expect(page.getByText('Fixture seating verified in simulation')).toBeVisible({timeout:45_000});
  await expect(page.getByTestId('branch-row')).toHaveCount(3);
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export verification record'}).click();
  const file=await download;
  const filePath=path.join(shots,'precision-report.json');
  await file.saveAs(filePath);
  const record=JSON.parse(fs.readFileSync(filePath,'utf8'));
  expect(record.validation_status).toBe('verified');
  expect(record.measurements.evaluation.placement_within_tolerance).toBe(true);
  expect(record.measurements.performance.simulation_steps).toBeGreaterThan(1000);
  expect(record.branch_ids).toHaveLength(4); // Three validations plus independent authoritative execution.
  expect(record.measurements.fresh_execution.success).toBe(true);
  const denied=await page.request.get(`http://127.0.0.1:8000/v1/robotics/experiments/${record.experiment_id}/report`);
  expect(denied.status()).toBe(403);
  await page.getByRole('button',{name:'Replay selected trajectory'}).click();
  await expect(page.getByRole('button',{name:'Pause replay'})).toBeVisible();
  await expect.poll(async()=>Number((await page.getByRole('slider',{name:'Replay time'}).inputValue()))).toBeGreaterThan(.25);
  await page.getByRole('button',{name:'Pause replay'}).click();
  const replaySlider=page.getByRole('slider',{name:'Replay time'});
  await replaySlider.focus();
  await replaySlider.press('End');
  await expect.poll(async()=>Number(await replaySlider.getAttribute('max'))-Number(await replaySlider.inputValue())).toBeLessThan(1e-9);
  await page.getByRole('button',{name:'Exit replay'}).click();
  await expect(page.getByRole('button',{name:'Replay selected trajectory'})).toBeVisible();
  await page.setViewportSize({width:390,height:850});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
  expect(a11y.violations).toEqual([]);
  await page.screenshot({path:path.join(shots,'precision-result-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1080});
  await page.getByRole('button',{name:'Change conditions'}).click();
  await page.getByText('Precision assembly tolerances and motion').click();
  await page.getByLabel('Placement tolerance (m)').fill('0.001');
  await page.getByRole('button',{name:'Apply settings'}).click();
  await expect(page.getByTestId('stale-warning')).toBeVisible({timeout:60_000});
  await page.getByRole('button',{name:'Start experiments'}).click();
  await expect(page.getByTestId('experiment-status')).toHaveText('No feasible result',{timeout:240_000});
  await expect(page.getByRole('heading',{name:'Precision assembly verification'})).toBeVisible({timeout:240_000});
  await expect(page.getByText('No verified placement')).toBeVisible({timeout:60_000});
  await expect(page.getByTestId('branch-row')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Pause simulation'})).toHaveCount(0,{timeout:45_000});
  await page.screenshot({path:path.join(shots,'precision-tight-tolerance.png'),fullPage:true});
  expect(errors).toEqual([]);
});
